"""Summarise a distillation run (results/distill/log.jsonl from 10_distill.py).

    .venv/bin/python -I scripts/distill_report.py          # print the curve
    .venv/bin/python -I scripts/distill_report.py --js     # also write learn/f-training-data.js
"""
import argparse
import json
from pathlib import Path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--log", default="results/distill/log.jsonl")
    ap.add_argument("--js", action="store_true")
    args = ap.parse_args()
    rows = [json.loads(line) for line in open(args.log)]
    train = [r for r in rows if "loss" in r]
    val = [r for r in rows if "val_kl" in r]
    for r in val:
        print(f"step {r['step']:3d}  validation KL {r['val_kl']:.4f}")
    if train:
        print(f"{len(train)} training steps, last KL {train[-1]['kl']:.4f}, {train[-1]['time'] / 60:.0f} min")
    if args.js:
        data = {"train": [{"step": r["step"], "kl": r["kl"], "lr": r["lr"], "grad_norm": r["grad_norm"]} for r in train],
                "val": [{"step": r["step"], "kl": r["val_kl"]} for r in val],
                "planned_steps": 62, "lr": 1e-4, "batch_tokens": 32 * 1024,
                "gradcheck": [{"layer": 39, "ratio": 0.90}, {"layer": 5, "ratio": 0.99}]}
        Path("learn/f-training-data.js").write_text(
            "/* Generated by scripts/distill_report.py --js from results/distill/log.jsonl. */\nconst TRAIN = "
            + json.dumps(data) + ";\n")
        print("wrote learn/f-training-data.js")


if __name__ == "__main__":
    main()
