"""Summarise results/bench.jsonl (from 08_bench.py) as one table, newest row per model and task.

    .venv/bin/python -I scripts/bench_report.py            # print the table
    .venv/bin/python -I scripts/bench_report.py --js        # also write learn/e-benchmark-data.js

The data file also carries a few real answers and failure counts for the appendix E page.
"""
import argparse
import collections
import json
from pathlib import Path

ORDER = ["original-q4", "general-k128", "distill-k128", "code-k48"]
NAMES = {"original-q4": "original 35 B (Q4_K_M)", "general-k128": "general prune 19 B",
         "distill-k128": "general prune 19 B + distilled routers", "code-k48": "code prune 8.9 B"}
TASKS = ["gsm8k", "humaneval", "mmlu"]


def load():
    best = {}
    for line in open("results/bench.jsonl"):
        row = json.loads(line)
        for task in TASKS:
            if task in row:
                best[(row["tag"], task)] = row[task]  # later rows win (re-runs)
    return best


def failures(tag, task):
    path = Path(f"results/bench/{tag}-{task}.jsonl")
    if not path.exists():
        return {}
    rows = [json.loads(line) for line in path.open()]
    c = collections.Counter()
    for r in rows:
        if r["ok"]:
            continue
        d = str(r["detail"] or "")
        if task == "humaneval":
            c["no code (rambled or looped)" if d == "no code block" else
              "wrong result" if d.startswith("AssertionError") else
              "typo / undefined name" if d.startswith("NameError") else
              "invented API / type error" if d.startswith(("AttributeError", "ImportError", "TypeError")) else
              "timeout" if d == "timeout" else "other crash"] += 1
        elif task == "gsm8k":
            c["ran past 2048 tokens" if r["tokens"] >= 2044 else "wrong number"] += 1
        else:
            c["wrong letter" if r["detail"] else "no letter"] += 1
    return dict(c)


def example(tag, task, item_id, chars=700):
    path = Path(f"results/bench/{tag}-{task}.jsonl")
    if not path.exists():
        return None
    for line in path.open():
        r = json.loads(line)
        if r["id"] == item_id:
            return {"ok": r["ok"], "detail": r["detail"], "answer": r["answer"][:chars]}
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--js", action="store_true")
    args = ap.parse_args()
    best = load()
    tags = [t for t in ORDER if any((t, k) in best for k in TASKS)]
    print(f"{'model':26s}" + "".join(f"{t:>24s}" for t in TASKS))
    for tag in tags:
        cells = []
        for task in TASKS:
            r = best.get((tag, task))
            cells.append(f"{r['score']:5.1f}% ({r['ci95'][0]:.0f}-{r['ci95'][1]:.0f})" if r else "-")
        print(f"{NAMES.get(tag, tag):26s}" + "".join(f"{c:>24s}" for c in cells))
    if args.js:
        data = {
            "names": NAMES, "tags": tags, "tasks": TASKS,
            "scores": {f"{t}|{k}": best[(t, k)] for t in tags for k in TASKS if (t, k) in best},
            "failures": {f"{t}|{k}": failures(t, k) for t in tags for k in TASKS},
            "examples": {
                "humaneval_18": {t: example(t, "humaneval", "HumanEval/18") for t in tags},
                "gsm8k_0": {t: example(t, "gsm8k", "gsm8k-0", 900) for t in tags},
            },
        }
        Path("learn/e-benchmark-data.js").write_text(
            "/* Generated by scripts/bench_report.py --js from results/bench*.jsonl. */\nconst BENCH = "
            + json.dumps(data, indent=1) + ";\n")
        print("wrote learn/e-benchmark-data.js")


if __name__ == "__main__":
    main()
