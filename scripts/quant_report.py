"""Step 4 report: join the quantization sweep (results/quant/sweep.jsonl), speed (results/speed.jsonl)
and benchmark (results/bench.jsonl) rows into one table, newest row per model and type.

    .venv/bin/python -I scripts/quant_report.py          # print the table
    .venv/bin/python -I scripts/quant_report.py --js     # also write learn/h-quant-data.js
"""
import argparse
import json
from pathlib import Path


def newest(path, key):
    out = {}
    if Path(path).exists():
        for line in open(path):
            row = json.loads(line)
            out[key(row)] = row
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--js", action="store_true")
    args = ap.parse_args()
    sweep = newest("results/quant/sweep.jsonl", lambda r: f"{r['tag']}-{r['quant']}")
    speed = newest("results/speed.jsonl", lambda r: r["tag"])
    bench = {}
    for line in open("results/bench.jsonl"):
        r = json.loads(line)
        for task in ("gsm8k", "humaneval", "mmlu"):
            if task in r:
                bench.setdefault(r["tag"], {})[task] = r[task]
    rows = []
    for key, r in sweep.items():
        row = dict(r)
        sp = speed.get(key, {})
        row["gen_tok_s"], row["prompt_tok_s"] = sp.get("gen_tok_s"), sp.get("prompt_tok_s")
        for task, v in bench.get(key, {}).items():
            row[task], row[task + "_ci"] = v["score"], v["ci95"]
        rows.append(row)
    # the unpruned original at Q4_K_M, benchmarked in step 2 (not part of this sweep)
    if "original-q4" in bench:
        row = {"tag": "orig", "quant": "Q4_K_M", "gib": 20.5, "bpw": round(20.5 * 2**30 * 8 / 34.6e9, 2),
               "ppl": None, "kld": None, "same_top_pct": None, "gen_tok_s": None, "prompt_tok_s": None}
        for task, v in bench["original-q4"].items():
            row[task], row[task + "_ci"] = v["score"], v["ci95"]
        rows.append(row)
    rows.sort(key=lambda r: (r["tag"] != "q128", -r["gib"]))

    head = f"{'model':6s} {'type':9s} {'GiB':>6s} {'bpw':>5s} {'ppl':>7s} {'KLD':>7s} {'top%':>6s} {'gen t/s':>8s} {'GSM8K':>6s} {'HEval':>6s} {'MMLU':>6s}"
    print(head)
    f = lambda v, d=2: "-" if v is None else f"{v:.{d}f}"  # noqa: E731
    for r in rows:
        print(f"{r['tag']:6s} {r['quant']:9s} {r['gib']:6.2f} {f(r['bpw']):>5s} {f(r['ppl'], 3):>7s} {f(r['kld'], 4):>7s} "
              f"{f(r['same_top_pct'], 1):>6s} {f(r['gen_tok_s'], 0):>8s} {f(r.get('gsm8k'), 1):>6s} {f(r.get('humaneval'), 1):>6s} {f(r.get('mmlu'), 1):>6s}")
    if args.js:
        Path("learn/h-quant-data.js").write_text(
            "/* Generated by scripts/quant_report.py --js from results/quant/sweep.jsonl, speed.jsonl, bench.jsonl. */\n"
            "const QUANT = " + json.dumps({"rows": rows, "gpu_gib": 16}) + ";\n")
        print("wrote learn/h-quant-data.js")


if __name__ == "__main__":
    main()
