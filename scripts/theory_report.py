"""Data for the foundation chapters 13-16 (attention and memory, number formats, speed, sampling).

Collects the measurements made for them into learn/theory-data.js:
  results/kv_memory.jsonl       scripts/kv_memory.sh      KV cache and DeltaNet state per context length
  results/batch_speed.jsonl     scripts/batch_speed.py    throughput against parallel requests
  results/speed.jsonl           scripts/speed_test.py     one-request speed per quantization (step 4)
  results/sampling_probs.json   (llama-server n_probs)    real next-token distributions, chat templates
  results/number_formats.json   scripts/number_formats.py real weights, activation ranges, addition order
  results/spec.jsonl, verify_cost.jsonl, spec_divergence.json   scripts/spec_sweep.sh, llama-bench: speculative decoding
plus the per-token read volume of the 19 B Q4_K_M GGUF (bytes of every tensor a generated token touches).

    .venv/bin/python -I scripts/theory_report.py
"""
import collections
import json
import sys
from pathlib import Path

sys.path.insert(0, "llama.cpp/gguf-py")


def rows(path):
    return [json.loads(line) for line in open(path)] if Path(path).exists() else []


def read_per_token(path, n_experts=128, top_k=8):
    """GiB a single generated token reads: every tensor except the embedding table (one row) and the routed
    experts (top_k of n_experts slices per layer)."""
    from gguf import GGUFReader
    cat = collections.Counter()
    for t in GGUFReader(path).tensors:
        n = t.name
        key = ("experts" if "_exps" in n else "embedding" if n.startswith("token_embd") else "lm_head" if n.startswith("output.")
               else "shared expert" if "_shexp" in n else "attention, DeltaNet, router, norms")
        cat[key] += int(t.n_bytes)
    gib = {k: v / 2**30 for k, v in cat.items()}
    per_token = sum(gib.values()) - gib["experts"] - gib["embedding"] + gib["experts"] * top_k / n_experts
    return {"parts_gib": {k: round(v, 3) for k, v in gib.items()}, "per_token_gib": round(per_token, 3),
            "experts_gib": round(gib["experts"], 3), "non_expert_gib": round(per_token - gib["experts"] * top_k / n_experts, 3)}


def main():
    cfg = json.loads(Path("models/Qwen3.5-35B-A3B/config.json").read_text())["text_config"] \
        if Path("models/Qwen3.5-35B-A3B/config.json").exists() else json.loads(Path("/mnt/f/qwen-scratch/q35-reap-k128/config.json").read_text())["text_config"]
    keys = ["num_hidden_layers", "full_attention_interval", "num_attention_heads", "num_key_value_heads", "head_dim",
            "linear_num_key_heads", "linear_num_value_heads", "linear_key_head_dim", "linear_value_head_dim",
            "linear_conv_kernel_dim", "hidden_size", "max_position_embeddings", "vocab_size"]
    size = {f"{r['tag']}-{r['quant']}": r["gib"] for r in rows("results/quant/sweep.jsonl")}  # file size per speed row
    out = {
        "config": {k: cfg[k] for k in keys},
        "kv_memory": rows("results/kv_memory.jsonl"),
        "batch_speed": rows("results/batch_speed.jsonl"),
        "speed": [dict(r, gib=size.get(r["tag"])) for r in rows("results/speed.jsonl")],
        "sampling": json.loads(Path("results/sampling_probs.json").read_text()),
        "numbers": json.loads(Path("results/number_formats.json").read_text()),
        "read": read_per_token("gguf/q35-reap-k128/q35-reap-k128-Q4_K_M.gguf"),
        "gpu": {"name": "RTX 5070 Ti", "bandwidth_gbs": 896, "vram_gib": 16},
        "spec": rows("results/spec.jsonl"),                       # spec_sweep.sh: speculative decoding per prompt
        "verify_cost": rows("results/verify_cost.jsonl"),         # llama-bench: ms for a pass over 1..16 tokens
        "spec_divergence": json.loads(Path("results/spec_divergence.json").read_text()) if Path("results/spec_divergence.json").exists() else None,
    }
    Path("learn/theory-data.js").write_text("/* Generated by scripts/theory_report.py from results/ (see its docstring). */\n"
                                            "const TH = " + json.dumps(out) + ";\n")
    print("read per token:", out["read"])
    print("wrote learn/theory-data.js")


if __name__ == "__main__":
    main()
