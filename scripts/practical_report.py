"""Data for appendix J (step 6): the any-model GGUF pipeline on Qwen3.5-2B, and the 35 B offload sweep.

    .venv/bin/python -I scripts/practical_report.py      # prints the tables, writes learn/j-practical-data.js
"""
import json
from pathlib import Path


def rows(path):
    return [json.loads(line) for line in open(path)] if Path(path).exists() else []


def main():
    make = rows("results/make_gguf.jsonl")
    off = rows("results/offload.jsonl")
    speed = {r["tag"]: r for r in rows("results/speed.jsonl")}
    sweep = {f"{r['tag']}-{r['quant']}": r for r in rows("results/quant/sweep.jsonl")}
    bench = {}
    for line in open("results/bench.jsonl"):
        r = json.loads(line)
        for t in ("gsm8k", "humaneval", "mmlu"):
            if t in r:
                bench.setdefault(r["tag"], {})[t] = r[t]["score"]
    avg = lambda b: round(sum(b.values()) / 3, 1) if len(b) == 3 else None  # noqa: E731
    refs = [  # models that fit entirely on the GPU, for comparison with the offloaded 35 B Q4_K_M
        {"name": "35 B UD-IQ3_XXS, all on GPU", "gib": sweep["orig-UD-IQ3_XXS"]["gib"], "gen_tok_s": speed["orig-UD-IQ3_XXS"]["gen_tok_s"], "avg": avg(bench.get("orig-UD-IQ3_XXS", {}))},
        {"name": "19 B pruned Q4_K_M, all on GPU", "gib": sweep["q128-Q4_K_M"]["gib"], "gen_tok_s": speed["q128-Q4_K_M"]["gen_tok_s"], "avg": avg(bench.get("q128-Q4_K_M", {}))},
    ]
    q4avg = avg(bench.get("original-q4", {}))
    print(f"{'type':10s} {'GiB':>6s} {'ppl':>8s}  (Qwen3.5-2B, wikitext-2 test)")
    for r in make:
        print(f"{r['type']:10s} {r['gib']:6.2f} {r['ppl'] if r['ppl'] is None else format(r['ppl'], '8.3f')}")
    print(f"\n{'setting':10s} {'GPU GiB':>8s} {'gen t/s':>8s} {'prompt t/s':>11s}  (35 B Q4_K_M, 20.5 GiB, avg score {q4avg})")
    for r in off:
        if r.get("error"):
            continue
        print(f"{r['setting']:10s} {r['gpu_weights_mib'] / 1024:8.1f} {r['speed']['gen_tok_s']:8.1f} {r['speed']['prompt_tok_s']:11.0f}")
    for r in refs:
        print(r)
    out = {"make": make, "offload": [r for r in off if not r.get("error")], "refs": refs, "q4_avg": q4avg,
           "file_gib": 20.5, "ram_gib": 32, "vram_gib": 16,
           "downloads": [{"what": "Qwen3.5-35B-A3B (safetensors, 67 GiB)", "minutes": 7.0},
                         {"what": "Qwen3.5-35B-A3B Q4_K_M GGUF (20.5 GiB)", "minutes": 3.1}]}
    Path("learn/j-practical-data.js").write_text("/* Generated by scripts/practical_report.py from results/make_gguf.jsonl, offload.jsonl, speed.jsonl, bench.jsonl. */\n"
                                                 "const PR = " + json.dumps(out) + ";\n")
    print("wrote learn/j-practical-data.js")


if __name__ == "__main__":
    main()
